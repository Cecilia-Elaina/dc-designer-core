# Main generator: assemble all materials
# ---------------------------------------------------------------------------

def _wrap_material(raw_content: dict, material_type: str, title: str,
                    target_users: list, objective_ids: list,
                    strategy_segments: list, assessment_ids: list,
                    time_minutes: int) -> dict:
    """Wrap raw material content in standard metadata structure."""
    return {
        'material_id': f'mat_{material_type}',
        'title': title,
        'material_type': material_type,
        'target_users': target_users,
        'related_objective_ids': objective_ids,
        'related_strategy_segments': strategy_segments,
        'related_assessment_ids': assessment_ids,
        'estimated_time_minutes': time_minutes,
        'content': raw_content,
        'usage_notes': [],
        'status': 'candidate',
    }


def generate_instructional_materials(project: dict) -> dict:
    """
    Generate all 9 material types and assemble into instructional_materials.
    Each material is wrapped with standard metadata fields.
    """
    objectives = project.get('objectives', [])
    obj_ids = [o.get('objective_id', '') for o in objectives if o.get('objective_id')]

    raw_materials = {
        'teacher_guide': generate_teacher_guide(project),
        'student_worksheet': generate_student_worksheet(project),
        'entry_test_sheet': generate_entry_test_sheet(project),
        'pretest_sheet': generate_pretest_sheet(project),
        'group_task_sheet': generate_group_task_sheet(project),
        'peer_review_checklist': generate_peer_review_checklist(project),
        'posttest_sheet': generate_posttest_sheet(project),
        'board_design': generate_board_design(project),
        'simple_lesson_plan': generate_simple_lesson_plan(project),
    }

    # Wrap each material with standard metadata
    materials = {}
    metadata_map = {
        'teacher_guide': ('teacher_guide', '教师授课手册', ['teacher'], obj_ids, ['全部'], ['all'], 45),
        'student_worksheet': ('student_worksheet', '学生学习单', ['student'], obj_ids, ['全部'], ['all'], 45),
        'entry_test_sheet': ('entry_test', '入门技能测试单', ['student'], obj_ids[:1], ['教学前活动'], ['entry_behavior_test'], 5),
        'pretest_sheet': ('pretest', '前测任务单', ['student'], obj_ids[:2], ['教学前活动'], ['pretest'], 5),
        'group_task_sheet': ('group_task', '小组任务单', ['student'], obj_ids, ['学习者参与'], ['practice_evidence'], 10),
        'peer_review_checklist': ('peer_review', '互评检查表', ['student'], obj_ids, ['学习者参与'], ['practice_evidence'], 5),
        'posttest_sheet': ('posttest', '后测任务单', ['student'], obj_ids, ['评估'], ['posttest'], 5),
        'board_design': ('board', '板书设计', ['teacher'], obj_ids, ['全部'], [], 0),
        'simple_lesson_plan': ('lesson_plan', '简版课堂教案', ['teacher'], obj_ids, ['全部'], ['all'], 45),
    }

    for key, raw_content in raw_materials.items():
        mt, title, users, oids, segs, aids, time = metadata_map[key]
        materials[key] = _wrap_material(
            raw_content, mt, title, users, oids, segs, aids, time
        )

    return materials
