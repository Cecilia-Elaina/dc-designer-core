# Chinese quotation marks as constants to avoid encoding issues
LQ = '“'  # left double quotation mark
RQ = '”'  # right double quotation mark


def _get_topic_material_config(project: dict) -> dict:
    """Extract topic-specific material configuration from project."""
    topic = project.get('topic', 'algorithm')
    return TOPIC_MATERIALS.get(topic, TOPIC_MATERIALS.get('algorithm', {}))


def _get_objectives_text(project: dict) -> list:
    """Extract learning objectives as readable string list."""
    objectives = project.get('objectives', project.get('learning_objectives', []))
    result = []
    for obj in objectives:
        if isinstance(obj, str):
            result.append(obj)
        elif isinstance(obj, dict):
            # Build readable text from objective dict fields
            behavior = obj.get('behavior', obj.get('description', ''))
            condition = obj.get('condition', '')
            criterion = obj.get('criterion', '')
            if behavior:
                text = behavior
                if condition:
                    text += f"（条件：{condition}）"
                if criterion:
                    text += f"【标准：{criterion}】"
                result.append(text)
            else:
                # Fallback: try text/description keys
                fallback = obj.get('text', obj.get('description', ''))
                if fallback:
                    result.append(fallback)
        else:
            result.append(str(obj))
    return result


def _get_strategy_flow(project: dict) -> list:
    """Extract lesson flow from instructional strategy."""
    strategy = project.get('instructional_strategy', {})
    return strategy.get('lesson_flow', [])


def _get_context(project: dict) -> dict:
    """Extract context analysis."""
    return project.get('context_analysis', {})


def _q(text: str) -> str:
    """Wrap text in Chinese quotation marks."""
    return LQ + text + RQ


